fun t(lang: AppLanguage, key: String): String {
    val dict = when (lang) {
        AppLanguage.AR -> AR_STRINGS
        AppLanguage.EN -> EN_STRINGS
        AppLanguage.FA -> FA_STRINGS
        AppLanguage.TR -> TR_STRINGS
    }
    return dict[key] ?: if (lang == AppLanguage.TR) {
        EN_STRINGS[key] ?: AR_STRINGS[key] ?: key
    } else {
        AR_STRINGS[key] ?: key
    }
}
